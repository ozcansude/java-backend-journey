CREATE VIEW v_movie_statistics AS
SELECT m.movie_id,m.title,m.release_date,
 COUNT(r.rating_id) AS rating_count,
 ROUND(AVG(r.rating)::numeric,2) AS avg_rating,
 COUNT(DISTINCT rv.review_id) AS review_count
FROM movies m LEFT JOIN ratings r ON r.movie_id=m.movie_id
LEFT JOIN reviews rv ON rv.movie_id=m.movie_id
GROUP BY m.movie_id,m.title,m.release_date;

CREATE VIEW v_rental_revenue AS
SELECT m.movie_id,m.title,
 COUNT(rt.rental_id) FILTER (WHERE rt.rental_status='completed') AS completed_rentals,
 COALESCE(SUM(p.amount_usd) FILTER (WHERE p.payment_status='paid'),0)::numeric(14,2) AS paid_revenue_usd
FROM movies m LEFT JOIN rentals rt ON rt.movie_id=m.movie_id
LEFT JOIN payments p ON p.rental_id=rt.rental_id
GROUP BY m.movie_id,m.title;

