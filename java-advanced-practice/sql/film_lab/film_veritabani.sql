BEGIN;
DROP SCHEMA IF EXISTS film_lab CASCADE;
CREATE SCHEMA film_lab;
SET search_path TO film_lab, public;

CREATE TABLE countries (
 country_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 country_name varchar(80) NOT NULL UNIQUE,
 iso_code char(2) NOT NULL UNIQUE
);
CREATE TABLE languages (
 language_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 language_name varchar(60) NOT NULL UNIQUE,
 iso_code varchar(5) NOT NULL UNIQUE
);
CREATE TABLE genres (
 genre_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 genre_name varchar(60) NOT NULL UNIQUE
);
CREATE TABLE studios (
 studio_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 studio_name varchar(120) NOT NULL UNIQUE,
 country_id int NOT NULL REFERENCES countries(country_id),
 founded_year smallint CHECK(founded_year BETWEEN 1900 AND 2026)
);
CREATE TABLE people (
 person_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 first_name varchar(60) NOT NULL,
 last_name varchar(60) NOT NULL,
 birth_date date,
 country_id int REFERENCES countries(country_id),
 gender varchar(20) CHECK(gender IN ('Female','Male','Nonbinary','Undisclosed'))
);
CREATE TABLE movies (
 movie_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title varchar(180) NOT NULL,
 release_date date NOT NULL,
 duration_minutes smallint NOT NULL CHECK(duration_minutes BETWEEN 40 AND 300),
 budget_usd numeric(14,2) CHECK(budget_usd >= 0),
 box_office_usd numeric(14,2) CHECK(box_office_usd >= 0),
 original_language_id int NOT NULL REFERENCES languages(language_id),
 country_id int NOT NULL REFERENCES countries(country_id),
 studio_id int REFERENCES studios(studio_id),
 age_rating varchar(10) CHECK(age_rating IN ('G','PG','PG-13','R','NC-17')),
 synopsis text,
 created_at timestamp NOT NULL DEFAULT current_timestamp
);
CREATE TABLE movie_genres (
 movie_id int NOT NULL REFERENCES movies(movie_id) ON DELETE CASCADE,
 genre_id int NOT NULL REFERENCES genres(genre_id),
 PRIMARY KEY(movie_id, genre_id)
);
CREATE TABLE movie_cast (
 movie_id int NOT NULL REFERENCES movies(movie_id) ON DELETE CASCADE,
 person_id int NOT NULL REFERENCES people(person_id),
 character_name varchar(100) NOT NULL,
 billing_order smallint NOT NULL CHECK(billing_order BETWEEN 1 AND 30),
 salary_usd numeric(12,2) CHECK(salary_usd >= 0),
 PRIMARY KEY(movie_id, person_id),
 UNIQUE(movie_id, billing_order)
);
CREATE TABLE movie_crew (
 movie_id int NOT NULL REFERENCES movies(movie_id) ON DELETE CASCADE,
 person_id int NOT NULL REFERENCES people(person_id),
 job varchar(30) NOT NULL CHECK(job IN ('Director','Writer','Producer','Composer','Cinematographer','Editor')),
 PRIMARY KEY(movie_id, person_id, job)
);
CREATE TABLE users (
 user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username varchar(60) NOT NULL UNIQUE,
 email varchar(120) NOT NULL UNIQUE,
 country_id int NOT NULL REFERENCES countries(country_id),
 registered_at timestamp NOT NULL,
 birth_date date,
 is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE subscriptions (
 subscription_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id int NOT NULL REFERENCES users(user_id),
 plan_name varchar(20) NOT NULL CHECK(plan_name IN ('Basic','Standard','Premium')),
 starts_on date NOT NULL,
 ends_on date,
 monthly_fee_usd numeric(7,2) NOT NULL CHECK(monthly_fee_usd >= 0),
 CHECK(ends_on IS NULL OR ends_on >= starts_on),
 UNIQUE(user_id, starts_on)
);
CREATE TABLE ratings (
 rating_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id int NOT NULL REFERENCES users(user_id),
 movie_id int NOT NULL REFERENCES movies(movie_id),
 rating smallint NOT NULL CHECK(rating BETWEEN 1 AND 10),
 rated_at timestamp NOT NULL,
 UNIQUE(user_id, movie_id)
);
CREATE TABLE reviews (
 review_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id int NOT NULL REFERENCES users(user_id),
 movie_id int NOT NULL REFERENCES movies(movie_id),
 review_text text NOT NULL,
 spoiler boolean NOT NULL DEFAULT false,
 created_at timestamp NOT NULL,
 UNIQUE(user_id, movie_id)
);
CREATE TABLE watchlists (
 user_id int NOT NULL REFERENCES users(user_id),
 movie_id int NOT NULL REFERENCES movies(movie_id),
 added_at timestamp NOT NULL,
 PRIMARY KEY(user_id, movie_id)
);
CREATE TABLE rentals (
 rental_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id int NOT NULL REFERENCES users(user_id),
 movie_id int NOT NULL REFERENCES movies(movie_id),
 rented_at timestamp NOT NULL,
 expires_at timestamp NOT NULL,
 returned_at timestamp,
 rental_status varchar(20) NOT NULL CHECK(rental_status IN ('completed','active','cancelled')),
 rental_price_usd numeric(7,2) NOT NULL CHECK(rental_price_usd >= 0),
 CHECK(expires_at > rented_at),
 CHECK(returned_at IS NULL OR returned_at >= rented_at)
);
CREATE TABLE payments (
 payment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 rental_id bigint NOT NULL UNIQUE REFERENCES rentals(rental_id),
 paid_at timestamp NOT NULL,
 amount_usd numeric(7,2) NOT NULL CHECK(amount_usd >= 0),
 payment_method varchar(20) NOT NULL CHECK(payment_method IN ('card','wallet','gift_card')),
 payment_status varchar(20) NOT NULL CHECK(payment_status IN ('paid','refunded','failed'))
);
CREATE TABLE awards (
 award_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 movie_id int NOT NULL REFERENCES movies(movie_id),
 person_id int REFERENCES people(person_id),
 award_name varchar(100) NOT NULL,
 category varchar(100) NOT NULL,
 award_year smallint NOT NULL CHECK(award_year BETWEEN 1950 AND 2030),
 is_winner boolean NOT NULL
);

